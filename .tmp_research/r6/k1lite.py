# -*- coding: utf-8 -*-
"""Scratch (R6 research): light K1 estimators — silero VAD (ONNX), WADA-SNR, deep-pause SNR, blind RT60.
No heavy models. Only numpy/scipy/onnxruntime."""
import os
import sys

import numpy as np
import onnxruntime as ort

SR = 16000
WIN = 0.03
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "blind_rt60_pkg"))

_SIL = None


def silero_prob(y):
    """Silero VAD v6 ONNX: prob per 512-sample chunk (32 ms) at 16 kHz."""
    global _SIL
    if _SIL is None:
        o = ort.SessionOptions(); o.intra_op_num_threads = 1; o.inter_op_num_threads = 1
        _SIL = ort.InferenceSession(os.path.join(HERE, "..", "models", "silero_vad.onnx"), o,
                                    providers=["CPUExecutionProvider"])
    n = len(y) // 512
    st = np.zeros((2, 1, 128), np.float32)
    ctx = np.zeros((1, 64), np.float32)
    sr = np.array(SR, np.int64)
    out = np.zeros(n, np.float32)
    y = y.astype(np.float32)
    for i in range(n):
        x = np.concatenate([ctx, y[None, i * 512:(i + 1) * 512]], 1)
        p, st = _SIL.run(None, {"input": x, "state": st, "sr": sr})
        out[i] = p[0, 0]
        ctx = x[:, -64:]
    return out


def to_frames(chunk_mask, n_frames, chunk_s=0.032):
    tc = (np.arange(n_frames) + 0.5) * WIN
    j = np.clip((tc / chunk_s).astype(int), 0, len(chunk_mask) - 1)
    return chunk_mask[j]


def frame_db(y):
    n = int(WIN * SR); k = len(y) // n
    f = y[:k * n].reshape(k, n).astype(np.float64)
    return 10 * np.log10((f ** 2).mean(1) + 1e-12)


def dilate(m, r):
    if r <= 0:
        return m.copy()
    k = np.ones(2 * r + 1)
    return np.convolve(m.astype(float), k, "same") > 0


def dist_to_speech(sp):
    """distance (frames) from each frame to nearest speech frame"""
    idx = np.where(sp)[0]
    if not len(idx):
        return np.full(len(sp), 10 ** 6)
    pos = np.arange(len(sp))
    j = np.searchsorted(idx, pos)
    a = np.abs(pos - idx[np.clip(j, 0, len(idx) - 1)])
    b = np.abs(pos - idx[np.clip(j - 1, 0, len(idx) - 1)])
    return np.minimum(a, b)


def snr_from_masks(pw, sp, nz, min_noise_s=1.0, stat="mean"):
    if not sp.any() or nz.sum() * WIN < min_noise_s:
        return None
    pn = np.mean(pw[nz]) if stat == "mean" else np.percentile(pw[nz], stat)
    return float(10 * np.log10(max(pw[sp].mean() - pn, 1e-12) / (pn + 1e-12)))


# ---------- WADA-SNR (Kim & Stern, Interspeech 2008): table G(SNR) regenerated by Monte Carlo ----------
_WADA = None


def wada_table(alpha=0.4, n=2_000_000, seed=0):
    rng = np.random.default_rng(seed)
    s = rng.gamma(alpha, 1.0, n) * rng.choice([-1.0, 1.0], n)
    z = rng.standard_normal(n)
    ps = alpha * (alpha + 1)
    dbs = np.arange(-20, 101, 1.0)
    g = []
    for d in dbs:
        x = s + z * np.sqrt(ps / 10 ** (d / 10))
        a = np.abs(x) + 1e-20
        g.append(np.log(a.mean()) - np.log(a).mean())
    return dbs, np.maximum.accumulate(np.array(g))


def wada_snr(y):
    global _WADA
    if _WADA is None:
        cache = os.path.join(HERE, "wada_table.npz")
        if os.path.exists(cache):
            z = np.load(cache); _WADA = (z["dbs"], z["g"])
        else:
            _WADA = wada_table(); np.savez(cache, dbs=_WADA[0], g=_WADA[1])
    dbs, g = _WADA
    a = np.abs(y.astype(np.float64)); a[a < 1e-10] = 1e-10
    v3 = np.log(a.mean()) - np.log(a).mean()
    if v3 <= g[0]:
        return float(dbs[0])
    if v3 >= g[-1]:
        return float(dbs[-1])
    return float(np.interp(v3, g, dbs))


# ---------- blind RT60: Ratnam et al. 2003 ML decay model (same likelihood as package blind_rt60),
# with Loellmann-2010-style pre-selection of free-decay frames + vectorised bisection (fast) ----------
def blind_rt60(y, pct=(10, 25, 50), fs=8000, flen=0.2, hop=0.05, nsub=4, iters=40):
    from scipy.signal import decimate
    x = decimate(y.astype(np.float64), SR // fs)
    L, H = int(flen * fs), int(hop * fs)
    if len(x) < L + H:
        return {**{p: None for p in pct}, "n": 0}
    idx = np.arange(0, len(x) - L + 1, H)
    F = np.stack([x[i:i + L] for i in idx])
    sub = (F[:, :L // nsub * nsub].reshape(len(F), nsub, -1) ** 2).mean(2) + 1e-20
    sdb = 10 * np.log10(sub)
    fdb = 10 * np.log10((F ** 2).mean(1) + 1e-20)
    keep = np.all(np.diff(sdb, axis=1) < 0, axis=1) & (sdb[:, 0] - sdb[:, -1] > 3) & (fdb > np.percentile(fdb, 20) + 6)
    F = F[keep]
    if len(F) < 3:
        return {**{p: None for p in pct}, "n": int(len(F))}
    n = np.arange(L, dtype=float)[None]
    fac = L * (L - 1) / 2

    def dl(a):  # d logL / da  (up to positive factor)
        ax = np.exp(-2 * n * np.log(a)) * F ** 2
        s2 = ax.mean(1, keepdims=True) + 1e-30
        return (ax * n).sum(1, keepdims=True) / s2 - fac
    lo = np.full((len(F), 1), 0.99); hi = np.full((len(F), 1), 0.9999999)
    for _ in range(iters):
        mid = 0.5 * (lo + hi)
        g = dl(mid)
        # dl decreasing in a around the ML point: g>0 -> a too small
        lo = np.where(g > 0, mid, lo); hi = np.where(g > 0, hi, mid)
    a = 0.5 * (lo + hi)[:, 0]
    tau = -1 / np.log(a) / fs
    rt = 6.9078 * tau
    rt = rt[(rt > 0.05) & (rt < 5)]
    if len(rt) < 3:
        return {**{p: None for p in pct}, "n": int(len(rt))}
    return {**{p: float(np.percentile(rt, p)) for p in pct}, "n": int(len(rt))}


def measure(y, do_rt60=True):
    """all light estimators on one mono 16 kHz signal"""
    db = frame_db(y); pw = 10 ** (db / 10)
    nf = len(db)
    floor = np.percentile(db, 10)
    sp_e = (db > floor + 10) & (db > -60)
    prob = silero_prob(y)
    sp_v = to_frames(prob > 0.5, nf)
    sp_vd = dilate(sp_v, 3)  # +-0.1 s like k1 ASR mask
    out = {}
    out["snr_energy"] = snr_from_masks(pw, sp_e, ~sp_e)
    sp = sp_vd & sp_e
    out["snr_silero"] = snr_from_masks(pw, sp, ~sp_vd)                      # k1 recipe, silero instead of ASR
    d = dist_to_speech(sp_v)
    out["snr_deep300"] = snr_from_masks(pw, sp, d >= 10, min_noise_s=0.3)    # >= 0.3 s from speech
    out["snr_p20"] = snr_from_masks(pw, sp, ~sp_vd, min_noise_s=0.3, stat=20)
    out["snr_p10all"] = snr_from_masks(pw, sp, np.ones(nf, bool), min_noise_s=0.3, stat=10)  # no VAD needed for noise
    out["snr_wada"] = wada_snr(y)
    out["noise_s_k1"] = float((~sp_vd).sum() * WIN)
    out["speech_s_silero"] = float(sp_v.sum() * WIN)
    out["speech_frac"] = float(sp_v.mean())
    if do_rt60:
        out.update({f"rt60_p{k}": v for k, v in blind_rt60(y).items()})
    return out
